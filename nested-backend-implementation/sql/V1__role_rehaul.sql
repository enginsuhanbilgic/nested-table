INSERT INTO stat.lr_role_pages (role_id, page_code)
SELECT r.id, p.code
  FROM stat.lr_roles r
       CROSS JOIN unnest(ARRAY ['LATENCY_DAILY', 'LATENCY_RTT', 'LATENCY_GROUPED']) AS p(code)
 WHERE r.code = 'STANDARD_USER'
UNION ALL
SELECT r.id, 'TRANSACTIONS' FROM stat.lr_roles r WHERE r.code = 'TRANSACTION'
UNION ALL
SELECT r.id, 'ANALYTICS' FROM stat.lr_roles r WHERE r.code = 'ANALYTICS';
