SELECT r.id,
       'İletişim Kanalları Servisi',
       'iletişim kanallari servisi',
       'EXACT',
       true,
       'Transaction pages for the communication channels service',
       'SYSTEM_SEED'
  FROM stat.lr_roles r
 WHERE r.code = 'TRANSACTION';

-- ============================================================================
-- Re-attach the user_page_history foreign key(s) captured at the top,
-- exactly as they were (same name, same columns, same ON DELETE behavior).
-- ============================================================================
DO $$
DECLARE
    fk record;
BEGIN
    FOR fk IN SELECT conname, definition FROM _uph_fk LOOP
        EXECUTE format(
            'ALTER TABLE stat.user_page_history ADD CONSTRAINT %I %s',
            fk.conname, fk.definition
        );
    END LOOP;
END $$;

DROP TABLE IF EXISTS _uph_fk;

